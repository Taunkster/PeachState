#!/usr/bin/env node
/**
 * generate-fixtures.mjs — data pipeline: fixtures JSON → typed TypeScript.
 *
 * Reads the canonical fixture JSONs (single source of truth for every number)
 * and emits `src/data/fixtures.generated.ts`, typed against `src/data/types.ts`.
 *
 * Sources (same contract as scripts/video_charts/chart_data.py):
 *   data/fixtures/dashboard/heat_frames.json  — 10 steps × 720 heat tiles
 *   data/fixtures/demo/fields_snapshot.json   — 45 fields
 *   data/fixtures/demo/corridor.json          — I-16 vs I-75
 *   data/fixtures/demo/alerts.json            — PV-07 CRITICAL + SMS
 *   data/fixtures/demo/kpis.json              — 4 KPI cards
 *   data/fixtures/dashboard/risk_data.json    — series + spoilage + radar
 *   data/crop_thresholds.json                 — Q10 / GDD / thresholds
 *   data/rehearsal/*_captions.json            — narration caption blocks
 *   data/rehearsal/*_timing.json              — master timing + key beats
 *
 * Deterministic: same inputs → identical output (sorted keys, fixed decimals).
 * Run: npm run fixtures:gen
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, ".."); // video/
const REPO = resolve(ROOT, ".."); // peachstate-coolchain/
const DST_DIR = resolve(ROOT, "src", "data");
const DST = resolve(DST_DIR, "fixtures.generated.ts");

const load = (p) => JSON.parse(readFileSync(resolve(REPO, p), "utf8"));

const HEAT = load("data/fixtures/dashboard/heat_frames.json");
const FIELDS = load("data/fixtures/demo/fields_snapshot.json");
const CORRIDOR = load("data/fixtures/demo/corridor.json").response ?? load("data/fixtures/demo/corridor.json");
const ALERTS = load("data/fixtures/demo/alerts.json");
const KPIS = load("data/fixtures/demo/kpis.json");
const RISK = load("data/fixtures/dashboard/risk_data.json");
const THRESHOLDS = load("data/crop_thresholds.json");
const CAPTIONS = load("data/rehearsal/peachstate_coolchain_demo_captions.json");
const TIMING = load("data/rehearsal/peachstate_coolchain_demo_timing.json");

/**
 * Parse "Narrator should land key beats at: 3.0s ($780M), 7.0s chip1, …"
 * (recording_notes) into structured { time_s, label } key-beat markers for
 * the ClickTrack voiceover metronome.
 */
function parseKeyBeats(notes) {
  const line = (notes ?? []).find((n) => typeof n === "string" && n.includes("key beats"));
  if (!line) return [];
  const after = line.split("at:")[1] ?? "";
  const beats = [];
  for (const part of after.split(",")) {
    const m = part.trim().match(/^(\d+(?:\.\d+)?)\s*s?\s*(?:\(([^)]+)\))?(.*)$/);
    if (!m) continue;
    const label = (m[2] ?? m[3] ?? "").trim().replace(/\.$/, "");
    beats.push({ time_s: parseFloat(m[1]), label: label || `beat @ ${m[1]}s` });
  }
  return beats;
}

const TIMING_DOC = {
  ...TIMING,
  key_beats: parseKeyBeats(TIMING.recording_notes),
};

/** Polygon centroid (tile cells are small squares — exact centroid is fine). */
function centroid(coords) {
  const ring = coords[0];
  let a = 0, cx = 0, cy = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const [x0, y0] = ring[i];
    const [x1, y1] = ring[i + 1];
    const f = x0 * y1 - x1 * y0;
    a += f;
    cx += (x0 + x1) * f;
    cy += (y0 + y1) * f;
  }
  a *= 0.5;
  return [cx / (6 * a), cy / (6 * a)]; // [lon, lat]
}

// --- Heat points (centroids of 720 tiles/hour → Deck.gl HeatmapLayer feed) ---
const heatPoints = {};
for (const [hour, feats] of Object.entries(HEAT.frames)) {
  heatPoints[hour] = feats.map((ft) => {
    const [lon, lat] = centroid(ft.geometry.coordinates);
    return {
      fieldId: ft.properties.field_id,
      hour: ft.properties.hour,
      lon: round(lon, 6),
      lat: round(lat, 6),
      tcmF: round(ft.properties.tcm_f, 1),
      riskScore: round(ft.properties.risk_score, 1),
      tier: ft.properties.tier,
    };
  });
}

function round(n, d) {
  const p = 10 ** d;
  return Math.round(n * p) / p;
}

const fmt = (o) => JSON.stringify(o, null, 1).replace(/"(\d+(?:\.\d+)?)"/g, "$1");

/**
 * Embed an object as `JSON.parse('...')` — avoids TS literal-type inference
 * (TS2590 "union too complex") on very large / heterogeneous arrays while
 * keeping the full type through the `as Type` assertion.
 */
const asJson = (o) => `JSON.parse('${JSON.stringify(o).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}')`;

const out = `/**
 * fixtures.generated.ts — AUTO-GENERATED by scripts/generate-fixtures.mjs. DO NOT EDIT.
 *
 * Typed fixture constants produced from the canonical JSON under
 * peachstate-coolchain/data/fixtures/ — every number in the demo video reads
 * from this module (single source of truth). Regenerate with \`npm run fixtures:gen\`.
 *
 * Generated: ${new Date().toISOString()}
 */
import type {
  HeatPoint,
  FieldSnapshot,
  CorridorFixture,
  AlertsFixture,
  KpisFixture,
  RiskDataFixture,
  CropThresholdsFixture,
  CaptionBlock,
  TimingDoc,
} from "./types";

/** 10 time steps 08:00–17:00 → heat tile centroids (720/hour) for Deck.gl HeatmapLayer. */
export const HEAT_POINTS_BY_HOUR: Record<string, HeatPoint[]> = ${asJson(heatPoints)};

/** 45 fields with risk + harvest windows (fields_snapshot.json). */
export const FIELDS: FieldSnapshot[] = ${asJson(FIELDS)};

/** I-16 vs I-75 corridor comparison (corridor.json). */
export const CORRIDOR: CorridorFixture = ${fmt(CORRIDOR)};

/** Harvest alerts + packing houses (alerts.json). */
export const ALERTS: AlertsFixture = ${fmt(ALERTS)};

/** 4 KPI cards + secondary metrics (kpis.json). */
export const KPIS: KpisFixture = ${fmt(KPIS)};

/** Risk time series (2160 rows) + Q10 spoilage curves + crop radar (risk_data.json). */
export const RISK_DATA: RiskDataFixture = ${asJson(RISK)};

/** Per-crop thresholds / Q10 / GDD (crop_thresholds.json). */
export const CROP_THRESHOLDS: CropThresholdsFixture = ${asJson(THRESHOLDS)};

/** 21 narration caption blocks (data/rehearsal/*_captions.json). */
export const CAPTIONS: CaptionBlock[] = ${asJson(CAPTIONS)};

/** Master timing doc: scenes, clicktrack spec, key beats (data/rehearsal/*_timing.json). */
export const TIMING: TimingDoc = ${asJson(TIMING_DOC)};
`;

mkdirSync(DST_DIR, { recursive: true });
writeFileSync(DST, out);
console.log(`fixtures:generated ${DST}`);
console.log(`  heat points  : ${Object.keys(heatPoints).length} hours × ${heatPoints["08:00"].length} tiles`);
console.log(`  fields       : ${FIELDS.length}`);
console.log(`  corridor     : ${CORRIDOR.routes.map((r) => r.route_id).join(", ")}`);
console.log(`  alerts       : ${ALERTS.alerts.length}`);
console.log(`  kpis         : ${KPIS.kpis.length}`);
console.log(`  risk series  : ${RISK.series.length} rows, spoilage ${RISK.spoilage.length}, radar ${RISK.crop_radar.length}`);
console.log(`  captions     : ${CAPTIONS.length} blocks, key beats ${TIMING_DOC.key_beats.length}, clicktrack ${TIMING_DOC.master.clicktrack.bpm} WPM`);